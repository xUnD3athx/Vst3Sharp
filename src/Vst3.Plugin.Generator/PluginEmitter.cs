using System.Collections.Generic;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Vst3.Plugin.Generator;

internal static class PluginEmitter
{
    public static string Emit(PluginModel model, bool hasEditor)
    {
        var sb = new StringBuilder();
        Line(sb, 0, "// <auto-generated/>");
        Line(sb, 0, "// Generated by Vst3.Plugin.Generator. Do not edit.");
        Line(sb, 0, "#nullable enable");
        Line(sb, 0, "#pragma warning disable CS0618");
        Line(sb, 0);

        int indent = 0;
        if (model.Namespace is not null)
        {
            Line(sb, 0, "namespace " + model.Namespace);
            Line(sb, 0, "{");
            indent = 1;
        }

        EmitBindings(sb, model, indent);
        Line(sb, 0);
        EmitModule(sb, model, hasEditor, indent);

        if (model.Namespace is not null)
            Line(sb, 0, "}");

        return sb.ToString();
    }

    private static void EmitBindings(StringBuilder sb, PluginModel model, int indent)
    {
        Line(sb, indent, "partial class " + model.ClassName);
        Line(sb, indent, "{");
        Line(sb, indent + 1, "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        Line(sb, indent + 1, "public override global::System.Collections.Generic.IReadOnlyList<global::Vst3.Plugin.ParameterDescriptor> DeclareParameters()");
        Line(sb, indent + 1, "{");
        Line(sb, indent + 2, "return new global::Vst3.Plugin.ParameterDescriptor[]");
        Line(sb, indent + 2, "{");
        foreach (ParameterModel parameter in model.Parameters)
        {
            Line(sb, indent + 3, "new global::Vst3.Plugin.ParameterDescriptor(");
            Line(sb, indent + 4, "Id: " + parameter.Index + ",");
            Line(sb, indent + 4, "Title: " + Literal(parameter.Title) + ",");
            Line(sb, indent + 4, "ShortTitle: " + Literal(parameter.ShortTitle) + ",");
            Line(sb, indent + 4, "Units: " + Literal(parameter.Units) + ",");
            Line(sb, indent + 4, "Min: " + Number(parameter.Min) + ",");
            Line(sb, indent + 4, "Max: " + Number(parameter.Max) + ",");
            Line(sb, indent + 4, "Default: " + Number(parameter.Default) + ",");
            Line(sb, indent + 4, "StepCount: " + parameter.StepCount + ",");
            Line(sb, indent + 4, "Flags: " + (parameter.CanAutomate ? "1" : "0") + "),");
        }

        Line(sb, indent + 2, "};");
        Line(sb, indent + 1, "}");
        Line(sb, 0);
        Line(sb, indent + 1, "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        Line(sb, indent + 1, "public override void BindParameters()");
        Line(sb, indent + 1, "{");
        foreach (ParameterModel parameter in model.Parameters)
            Line(sb, indent + 2, "Bind(" + parameter.Index + ", " + parameter.FieldName + ");");

        Line(sb, indent + 1, "}");
        Line(sb, indent, "}");
    }

    private static void EmitModule(StringBuilder sb, PluginModel model, bool hasEditor, int indent)
    {
        var arguments = new List<string>
        {
            "Name: " + Literal(model.Name),
            "ClassId: new global::System.Guid(" + Literal(model.ClassId) + ")",
            "Vendor: " + Literal(model.Vendor),
            "Url: " + Literal(model.Url),
            "Email: " + Literal(model.Email),
            "SubCategories: " + Literal(model.SubCategories),
            "Version: " + Literal(model.Version),
            "CreatePlugin: static () => new " + model.FullTypeName + "()",
            "Kind: global::Vst3.PluginKind." + (model.IsInstrument ? "Instrument" : "Effect"),
        };

        if (hasEditor)
            arguments.Add("ViewFactory: new global::Vst3.Editor.ImGuiEditorFactory()");

        Line(sb, indent, "public static unsafe class Vst3Module");
        Line(sb, indent, "{");
        Line(sb, indent + 1, "private static readonly global::Vst3.Plugin.PluginDescriptor s_descriptor = new(");
        for (int i = 0; i < arguments.Count; i++)
            Line(sb, indent + 2, arguments[i] + (i == arguments.Count - 1 ? "" : ","));

        Line(sb, indent + 1, ");");
        Line(sb, 0);
        EmitExport(sb, indent, "GetPluginFactory", "void*", new[]
        {
            "global::Vst3.Plugin.Vst3Plugin.Configure(s_descriptor);",
            "return global::Vst3.Plugin.Vst3Plugin.GetFactory();",
        });
        Line(sb, 0);
        EmitExport(sb, indent, "InitDll", "byte", new[] { "return 1;" });
        Line(sb, 0);
        EmitExport(sb, indent, "ExitDll", "byte", new[] { "return 1;" });
        Line(sb, indent, "}");
    }

    private static void EmitExport(StringBuilder sb, int indent, string entryPoint, string returnType, string[] body)
    {
        Line(sb, indent + 1, "[global::System.Runtime.InteropServices.UnmanagedCallersOnly(");
        Line(sb, indent + 2, "EntryPoint = " + Literal(entryPoint) + ",");
        Line(sb, indent + 2, "CallConvs = new[] { typeof(global::System.Runtime.CompilerServices.CallConvStdcall) })]");
        Line(sb, indent + 1, "public static " + returnType + " " + entryPoint + "()");
        Line(sb, indent + 1, "{");
        foreach (string line in body)
            Line(sb, indent + 2, line);

        Line(sb, indent + 1, "}");
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Number(double value) => value.ToString("R", CultureInfo.InvariantCulture) + "D";

    private static void Line(StringBuilder sb, int indent, string text = "")
    {
        for (int i = 0; i < indent; i++)
            sb.Append("    ");

        sb.AppendLine(text);
    }
}
